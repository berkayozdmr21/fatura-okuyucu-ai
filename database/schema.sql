-- Fatura Okuyucu - PostgreSQL şeması
-- API'deki SQLAlchemy modelleri (api/app/models.py) ile birebir aynı yapıdadır.
-- Geliştirmede API SQLite ile otomatik tablo oluşturur; üretimde bu dosya kullanılır.

BEGIN;

CREATE TABLE IF NOT EXISTS organizations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT        NOT NULL,
    -- Müşterilerin muhasebe bürosuna katılırken kullandığı kod
    invite_code  TEXT        NOT NULL UNIQUE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id         BIGINT      NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    email          TEXT        NOT NULL,
    password_hash  TEXT        NOT NULL,
    full_name      TEXT        NOT NULL,
    role           TEXT        NOT NULL CHECK (role IN ('accountant', 'client')),
    is_active      BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email_lower ON users (lower(email));
CREATE INDEX IF NOT EXISTS ix_users_org ON users (org_id);

CREATE TABLE IF NOT EXISTS documents (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id            BIGINT      NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    uploader_id       BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    original_filename TEXT        NOT NULL,
    mime_type         TEXT        NOT NULL,
    size_bytes        BIGINT      NOT NULL,
    sha256            TEXT        NOT NULL,
    storage_path      TEXT,                       -- NULL: dosya silinmiş, veri kalmış
    status            TEXT        NOT NULL DEFAULT 'uploaded'
                      CHECK (status IN ('uploaded','processed','needs_review','approved','rejected','failed')),
    extractor         TEXT,                       -- ubl_xml | pdf_text | ocr | llm
    data              JSONB       NOT NULL DEFAULT '{}'::jsonb,   -- çıkarılan fatura alanları
    field_confidence  JSONB       NOT NULL DEFAULT '{}'::jsonb,   -- alan bazında güven (0-1)
    issues            JSONB       NOT NULL DEFAULT '[]'::jsonb,   -- doğrulama uyarıları
    needs_review      BOOLEAN     NOT NULL DEFAULT FALSE,
    reviewed_by       BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at       TIMESTAMPTZ,
    expires_at        TIMESTAMPTZ,                -- KVKK: dosyanın silineceği zaman
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Aynı dosya aynı büroya iki kez yüklenemez
    CONSTRAINT ux_documents_org_sha UNIQUE (org_id, sha256)
);
CREATE INDEX IF NOT EXISTS ix_documents_org_status ON documents (org_id, status);
CREATE INDEX IF NOT EXISTS ix_documents_uploader   ON documents (uploader_id);
-- Aynı satıcı + fatura numarası tekrarını yakalamak için
CREATE INDEX IF NOT EXISTS ix_documents_invoice_key
    ON documents (org_id, (data->>'seller_vkn'), (data->>'invoice_no'));
CREATE INDEX IF NOT EXISTS ix_documents_expires ON documents (expires_at) WHERE storage_path IS NOT NULL;

CREATE TABLE IF NOT EXISTS audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      BIGINT      REFERENCES organizations(id) ON DELETE CASCADE,
    user_id     BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    document_id BIGINT      REFERENCES documents(id) ON DELETE SET NULL,
    action      TEXT        NOT NULL,             -- upload | view | edit | approve | delete | export
    detail      JSONB       NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_audit_org_time ON audit_log (org_id, created_at DESC);

COMMIT;
